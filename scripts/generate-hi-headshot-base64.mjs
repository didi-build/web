import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const pngPath = join(root, "public/didi.png");
const outPath = join(root, "src/content/hi-headshot-base64.ts");

const base64 = readFileSync(pngPath).toString("base64");

const contents = `/** Generated by scripts/generate-hi-headshot-base64.mjs — do not edit by hand. */
export const HI_HEADSHOT_PNG_BASE64 = ${JSON.stringify(base64)};
export const HI_HEADSHOT_MIME = "image/png";
`;

writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} from public/didi.png`);
