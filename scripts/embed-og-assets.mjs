import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const vines = readFileSync(join(root, "src/assets/og/og-vines.svg"), "utf8");
const semiBold = readFileSync(join(root, "src/assets/fonts/figtree/Figtree-SemiBold.ttf"));
const bold = readFileSync(join(root, "src/assets/fonts/figtree/Figtree-Bold.ttf"));

const out = `// Generated by scripts/embed-og-assets.mjs — do not edit by hand.
export const ogVinesSvg = ${JSON.stringify(vines)};

export const figtreeSemiBoldFont = Buffer.from(
  ${JSON.stringify(semiBold.toString("base64"))},
  "base64",
);

export const figtreeBoldFont = Buffer.from(
  ${JSON.stringify(bold.toString("base64"))},
  "base64",
);
`;

writeFileSync(join(root, "src/lib/og-assets.generated.ts"), out);
console.log("Wrote src/lib/og-assets.generated.ts");
